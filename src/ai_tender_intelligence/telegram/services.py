"""Replaceable ports; persistence, providers and production jobs come later."""

from datetime import datetime
from typing import Protocol

from .models import Company, Delivery, HistoryEntry, Job, ProfileFields, Tender


class BusinessProfiles(Protocol):
    def companies(self, user: int) -> tuple[Company, ...]: ...
    def company(self, user: int, company: str) -> Company: ...
    def create_company(self, user: int, fields: ProfileFields, *, confirmation_key: str | None = None) -> Company: ...
    def edit_fields(self, user: int, company: str, **changes) -> None: ...
    def delete_company(self, user: int, company: str) -> None: ...


class Classifications(Protocol):
    def classification_pending(self, user: int, company: str) -> bool: ...
    def classification_result(self, user: int, company: str) -> str: ...
    def reclassify(self, user: int, company: str, fields: ProfileFields, *, confirmation_key: str | None = None,
                   expected_revision: int | None = None) -> None: ...


class TenderSearch(Protocol):
    def search_results(self, user: int, company: str) -> tuple[Tender, ...]: ...
    def tender(self, tender: str) -> Tender: ...


class SavedHistory(Protocol):
    def set_saved(self, user: int, company: str, tender: str, saved: bool) -> None: ...
    def entries(self, user: int, company: str) -> tuple[HistoryEntry, ...]: ...


class Analyses(Protocol):
    def accept_analysis(self, user: int, company: str, tender: str, request_key: str) -> Job: ...
    def job(self, user: int, company: str, job: str) -> Job: ...
    def retry_analysis(self, user: int, company: str, job: str) -> Job: ...


class ReportDeliveries(Protocol):
    def deliver(self, user: int, company: str, job: str, historical: bool = False) -> Delivery: ...
    def delivery(self, user: int, company: str, delivery: str) -> Delivery: ...
    def published(self, user: int, company: str, delivery: str, message: str, at: datetime) -> None: ...
    def respond(self, user: int, company: str, delivery: str, received: bool) -> Delivery: ...
    def expire_receipt(self, user: int, company: str, delivery: str) -> bool: ...


class Services(Protocol):
    profiles: BusinessProfiles
    classifications: Classifications
    search: TenderSearch
    history: SavedHistory
    analyses: Analyses
    deliveries: ReportDeliveries
